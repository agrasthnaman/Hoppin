// Turns palettes.json into the stylesheet that defines the colour tokens (CSS variables) for every palette and mode.
// Run `npm run gen:theme -w apps/web` after editing palettes.json. A test checks the committed stylesheet is up to date.

const VARS = {
  bg: "--bg", surface: "--surface", surface2: "--surface-raised", ink: "--fg", muted: "--muted", line: "--line",
  accent: "--accent", accentFg: "--accent-fg", accentSoft: "--accent-soft", accentSoftFg: "--accent-soft-fg", link: "--link",
  hero: "--hero", heroFg: "--hero-fg", heroMuted: "--hero-muted", highlight: "--highlight", highlightFg: "--highlight-fg",
  nav: "--nav", navFg: "--nav-fg", navActive: "--nav-active",
};
const STATUS = { infoBg: "--info-bg", infoFg: "--info-fg", warnBg: "--warn-bg", warnFg: "--warn-fg", dangerBg: "--danger-bg", dangerFg: "--danger-fg" };

const declarations = (colors, status) =>
  [...Object.entries(VARS).map(([k, v]) => `  ${v}: ${colors[k]};`), ...Object.entries(STATUS).map(([k, v]) => `  ${v}: ${status[k]};`)].join("\n");

export function themeCss(data) {
  const out = ["/* GENERATED by scripts/gen-theme.mjs from src/theme/palettes.json. Do not edit by hand. */\n"];
  for (const p of data.palettes) {
    const isDefault = p.id === data.defaultPalette;
    const attr = `[data-palette="${p.id}"]`;
    const light = declarations(p.light, data.status.light);
    const dark = declarations(p.dark, data.status.dark);
    // Light values are the base. An element (normally <html>) with data-palette gets that palette's colours.
    out.push(`/* ${p.name}${isDefault ? " (default)" : ""} */`);
    out.push(`${isDefault ? ":root:not([data-palette]),\n" : ""}${attr} {\n${light}\n}\n`);
    // Dark only when the person chose it. The phone's own light or dark setting is not followed.
    out.push(`${isDefault ? ':root:not([data-palette])[data-theme="dark"],\n' : ""}${attr}[data-theme="dark"] {\n${dark}\n}\n`);
  }
  return out.join("\n");
}
